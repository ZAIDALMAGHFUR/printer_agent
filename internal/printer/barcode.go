// EncodeCode128B mengonversi string teks menjadi deretan baris bit (true = bar hitam, false = spasi putih)
func EncodeCode128B(text string) []bool {
	if text == "" {
		return nil
	}

	var codes []int
	codes = append(codes, 104) // Start Code B

	for _, ch := range []byte(text) {
		val := int(ch) - 32
		if val < 0 || val > 95 {
			val = 0
		}
		codes = append(codes, val)
	}

	// Hitung Checksum
	checksum := codes[0]
	for i := 1; i < len(codes); i++ {
		checksum += i * codes[i]
	}
	checksum = checksum % 103
	codes = append(codes, checksum)

	// Bangun modul bit
	var modules []bool

	// Quiet zone awal (10 modul)
	for i := 0; i < 10; i++ {
		modules = append(modules, false)
	}

	for _, code := range codes {
		p := code128Patterns[code]
		for step := 0; step < 6; step++ {
			isBar := (step % 2) == 0
			width := p[step]
			for w := 0; w < width; w++ {
				modules = append(modules, isBar)
			}
		}
	}

	// Simbol STOP (khusus: [2, 3, 3, 1, 1, 1, 2])
	stopWidths := []int{2, 3, 3, 1, 1, 1, 2}
	for step := 0; step < 7; step++ {
		isBar := (step % 2) == 0
		width := stopWidths[step]
		for w := 0; w < width; w++ {
			modules = append(modules, isBar)
		}
	}

	// Quiet zone akhir (10 modul)
	for i := 0; i < 10; i++ {
		modules = append(modules, false)
	}

	return modules
}

